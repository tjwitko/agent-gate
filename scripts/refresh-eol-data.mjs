#!/usr/bin/env node
// Regenerates agent/eol-data.mjs from endoflife.date.
//
//   node scripts/refresh-eol-data.mjs
//
// The dockerfile check blocks on a base image past its end of life, so the dates are the check.
// They come from endoflife.date's API rather than being typed in: a hand-maintained table is one
// typo from blocking a supported release, or passing an abandoned one.
//
// Fetched at release time, not at run time. The gate runs in CI and in pre-commit hooks, often
// offline, and a check whose verdict depends on a third-party API being up would be could-not-run
// whenever it is not. A stale table degrades gently: dates already in it pass on schedule, and a
// release newer than the table is simply not judged.
import { writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

// Docker Hub repository -> endoflife.date product, and how much of a tag is the release cycle.
export const PRODUCTS = {
  node: { api: "nodejs", label: "Node.js", parts: 1 },
  python: { api: "python", label: "Python", parts: 2 },
  golang: { api: "go", label: "Go", parts: 2 },
  ruby: { api: "ruby", label: "Ruby", parts: 2 },
  php: { api: "php", label: "PHP", parts: 2 },
  debian: { api: "debian", label: "Debian", parts: 1 },
  ubuntu: { api: "ubuntu", label: "Ubuntu", parts: 2 },
  alpine: { api: "alpine-linux", label: "Alpine Linux", parts: 2 },
  "eclipse-temurin": { api: "eclipse-temurin", label: "Eclipse Temurin (Java)", parts: 1 },
};

const date = (v) => (typeof v === "string" ? v : v === true ? true : false);

async function main() {
  const out = {};
  for (const [image, p] of Object.entries(PRODUCTS)) {
    const res = await fetch(`https://endoflife.date/api/${p.api}.json`);
    if (!res.ok) throw new Error(`${p.api}: HTTP ${res.status}`);
    const cycles = await res.json();
    out[image] = cycles.map((c) => ({
      cycle: String(c.cycle),
      // Lower-cased first word: Debian tags say `bookworm`, Ubuntu tags say `jammy`.
      ...(c.codename ? { codename: String(c.codename).split(/\s+/)[0].toLowerCase() } : {}),
      released: c.releaseDate || null,
      eol: date(c.eol),
      ...(c.lts ? { lts: true } : {}),
    }));
  }
  const fetched = new Date().toISOString().slice(0, 10);
  const body =
    `// GENERATED by scripts/refresh-eol-data.mjs from https://endoflife.date on ${fetched}. Do not edit by hand.\n` +
    `// \`eol\` is a date, true (ended, date unknown) or false (no end announced).\n` +
    `export const EOL_FETCHED = ${JSON.stringify(fetched)};\n\n` +
    `export const PRODUCTS = ${JSON.stringify(Object.fromEntries(Object.entries(PRODUCTS).map(([k, v]) => [k, { label: v.label, parts: v.parts }])), null, 2)};\n\n` +
    `export const EOL = ${JSON.stringify(out, null, 2)};\n`;
  const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "agent", "eol-data.mjs");
  writeFileSync(dest, body);
  console.log(`wrote ${path.relative(process.cwd(), dest)}: ${Object.values(out).reduce((n, c) => n + c.length, 0)} cycles across ${Object.keys(out).length} images, fetched ${fetched}`);
}

await main();
